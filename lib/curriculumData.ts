export function getChapters(exam?: ExamTarget, grade?: GradeLevel | "both", subject?: CompetitiveSubject): Chapter[] {
  return CHAPTERS_DATABASE.filter((ch) => {
    if (exam && !ch.exams.includes(exam)) return false
    if (grade && grade !== "both" && ch.grade !== grade) return false
    if (subject && ch.subject !== subject) return false
    return true
  }).sort((a, b) => {
    const [aSubject, aGrade, aNumber] = a.id.split("-")
    const [bSubject, bGrade, bNumber] = b.id.split("-")
    return (
      aSubject.localeCompare(bSubject) ||
      Number(aGrade) - Number(bGrade) ||
      Number(aNumber) - Number(bNumber)
    )
  })
}
